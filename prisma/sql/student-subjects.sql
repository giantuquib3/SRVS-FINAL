-- ============================================================================
-- SRVS migration: replace class_sections + enrollments with student_subjects
--
--   Before:  users ──< enrollments >── class_sections >── subjects
--   After:   users ──< student_subjects >── subjects
--
-- * Every (studentId, subjectId) pair from enrollments is copied into student_subjects.
-- * syllabi keeps subjectId (and its own academicYear / semester / section columns);
--   only syllabi.classSectionId and its foreign key are removed.
-- * class_sections and enrollments are dropped after the data is copied.
--
-- Run with:  node scripts/migrate-to-student-subjects.js
--            (backs up the affected tables and pre-checks the data first, then runs
--             everything below in ONE transaction and verifies the row count before commit)
-- ============================================================================

BEGIN;

-- 1. New junction table --------------------------------------------------------------
CREATE TABLE public.student_subjects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "studentId" integer NOT NULL,
    "subjectId" integer NOT NULL,
    "createdAt" timestamp without time zone
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_student_subjects_student
        FOREIGN KEY ("studentId")
        REFERENCES public.users(id),

    CONSTRAINT fk_student_subjects_subject
        FOREIGN KEY ("subjectId")
        REFERENCES public.subjects(id),

    CONSTRAINT uq_student_subjects
        UNIQUE ("studentId", "subjectId")
);

-- "Which students take subject X" lookups (studentId lookups use the unique index).
CREATE INDEX "student_subjects_subjectId_idx" ON public.student_subjects ("subjectId");

-- 2. Copy existing enrollments ------------------------------------------------------------
INSERT INTO public.student_subjects ("studentId", "subjectId", "createdAt")
SELECT DISTINCT ON (e."studentId", cs."subjectId") e."studentId", cs."subjectId", e."createdAt"
  FROM public.enrollments e
  JOIN public.class_sections cs ON cs.id = e."classSectionId"
 ORDER BY e."studentId", cs."subjectId", e."createdAt";

-- 3. Only users with role 'Student' can be associated with subjects -----------------------
-- (Duplicates are handled by uq_student_subjects; unknown IDs by the foreign keys.)
CREATE OR REPLACE FUNCTION enforce_student_subject_rules() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
  v_role TEXT;
BEGIN
  SELECT "role" INTO v_role FROM public.users WHERE "id" = NEW."studentId";
  IF v_role IS NOT NULL AND v_role <> 'Student' THEN
    RAISE EXCEPTION 'ENROLL_NOT_STUDENT: user % has role %, only Students can be associated with subjects', NEW."studentId", v_role;
  END IF;
  RETURN NEW; -- unknown user: fk_student_subjects_student rejects the row
END
$fn$;

CREATE TRIGGER "student_subjects_enforce_rules"
  BEFORE INSERT OR UPDATE OF "studentId" ON public.student_subjects
  FOR EACH ROW EXECUTE FUNCTION enforce_student_subject_rules();

-- Block the public Supabase REST API (anon / authenticated roles); the app connects as the
-- table owner through Prisma, which is not subject to row level security.
ALTER TABLE public.student_subjects ENABLE ROW LEVEL SECURITY;

-- 4. Detach syllabi from class sections ---------------------------------------------------
ALTER TABLE public.syllabi DROP CONSTRAINT IF EXISTS "syllabi_classSectionId_fkey";
DROP INDEX IF EXISTS public."syllabi_classSectionId_idx";
ALTER TABLE public.syllabi DROP COLUMN IF EXISTS "classSectionId";

-- 5. Remove the old tables (their triggers, CHECK constraints and RLS policies go with them)
DROP TABLE public.enrollments;
DROP TABLE public.class_sections;
DROP FUNCTION IF EXISTS enforce_enrollment_rules();

COMMIT;
